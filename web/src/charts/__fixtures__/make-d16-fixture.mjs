// FIXTURE GENERATOR (L08). Not part of the app or the pipeline.
// Writes d16.fixture.ts: stand-in values for the D16 fields (optimal_from,
// optimal_to, look_day) that L09 will publish in days.json. The rule copies
// D16's wording so the charts can be finished before L09 lands:
//   zone = contiguous days around days.best_day whose profit is within
//          (1 - ZONE_SHARE) of the best profit, only when the best profit is
//          above zero (a zone of loss-making days would read as "good");
//   look = first day >= LOOK_PCT red.
// Delete this file and the fixture once days.json carries the real fields.
// Run: node src/charts/__fixtures__/make-d16-fixture.mjs (from web/)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const data = join(here, '../../../../app/data');
const ZONE_SHARE = 0.9; // D16 economics.optimal_zone_share (fixture copy)
const LOOK_PCT = 70; // lower edge of logistics.best_band_pct_red (fixture copy)

const days = JSON.parse(readFileSync(join(data, 'days.json'), 'utf8')).rows;
const fc = JSON.parse(readFileSync(join(data, 'forecast.json'), 'utf8')).rows;
const byKey = new Map();
for (const r of fc) {
  const k = `${r.room}|${r.today}`;
  if (!byKey.has(k)) byKey.set(k, []);
  byKey.get(k).push(r);
}
const out = {};
for (const d of days) {
  const rows = (byKey.get(`${d.room}|${d.today}`) || []).sort((a, b) => a.date.localeCompare(b.date));
  const bi = rows.findIndex((r) => r.date === d.best_day);
  let from = null;
  let to = null;
  if (bi >= 0 && rows[bi].profit_m2_day > 0) {
    const best = rows[bi].profit_m2_day;
    const floor = best * ZONE_SHARE;
    let lo = bi;
    let hi = bi;
    while (lo > 0 && rows[lo - 1].profit_m2_day >= floor) lo--;
    while (hi < rows.length - 1 && rows[hi + 1].profit_m2_day >= floor) hi++;
    from = rows[lo].date;
    to = rows[hi].date;
  }
  const look = rows.find((r) => r.pct_red >= LOOK_PCT);
  out[`${d.room}|${d.today}`] = { optimal_from: from, optimal_to: to, look_day: look ? look.date : null };
}
const body = `// FIXTURE — generated by make-d16-fixture.mjs, NOT pipeline output.
// Stand-in for the D16 days.json fields until L09 publishes them.
// Keys are "room|today".
import type { D16Fields } from '../types';

export const D16_FIXTURE_IS_FIXTURE = true as const;

export const d16Fixture: Record<string, D16Fields> = ${JSON.stringify(out, null, 0).replace(/\},/g, '},\n  ')};
`;
writeFileSync(join(here, 'd16.fixture.ts'), body);
console.log('wrote', Object.keys(out).length, 'rows');
